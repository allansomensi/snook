#!/usr/bin/env python3
"""Generates the country list (crates/proto/src/countries.rs) and the flag atlas
(crates/client/assets/flags.png).

Requirements: `pip install pycountry pillow`, `rsvg-convert` (librsvg) and the
`flag-icons` npm package unpacked somewhere:

    npm pack flag-icons@7.2.3 && tar xzf flag-icons-7.2.3.tgz
    python3 tools/gen_countries.py path/to/package/flags/4x3
"""
import gettext
import os
import subprocess
import sys
import tempfile

import pycountry
from PIL import Image

FLAG_W, FLAG_H, COLS = 48, 36, 16
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main(svg_dir):
    pt = gettext.translation("iso3166-1", pycountry.LOCALES_DIR, languages=["pt_BR"])
    rows = []
    for c in pycountry.countries:
        svg = os.path.join(svg_dir, c.alpha_2.lower() + ".svg")
        if not os.path.exists(svg):
            continue
        en = getattr(c, "common_name", None) or c.name
        pt_name = pt.gettext(en)
        if pt_name == en:
            pt_name = pt.gettext(c.name)
        rows.append((c.alpha_2, en, pt_name, svg))
    rows.sort(key=lambda r: r[1])
    count = len(rows)
    atlas = Image.new("RGBA", (COLS * FLAG_W, ((count + COLS - 1) // COLS) * FLAG_H))
    with tempfile.TemporaryDirectory() as tmp:
        for i, (code, _, _, svg) in enumerate(rows):
            png = os.path.join(tmp, code + ".png")
            subprocess.run(["rsvg-convert", "-w", str(FLAG_W), "-h", str(FLAG_H), "-o", png, svg], check=True)
            atlas.paste(Image.open(png).convert("RGBA"), ((i % COLS) * FLAG_W, (i // COLS) * FLAG_H))
    atlas.save(os.path.join(ROOT, "crates/client/assets/flags.png"), optimize=True)

    def esc(s):
        return s.replace("\\", "\\\\").replace('"', '\\"')

    out = [
        "// Generated by tools/gen_countries.py: do not edit by hand.",
        "",
        "/// Flag atlas layout (crates/client/assets/flags.png): flags of",
        "/// `FLAG_W`×`FLAG_H` pixels, `FLAG_COLUMNS` per row, in the order of [`COUNTRIES`].",
        f"pub const FLAG_W: u32 = {FLAG_W};",
        f"pub const FLAG_H: u32 = {FLAG_H};",
        f"pub const FLAG_COLUMNS: u32 = {COLS};",
        "",
        "/// ISO 3166-1 alpha-2 code, English name, Brazilian Portuguese name.",
        "pub const COUNTRIES: &[(&str, &str, &str)] = &[",
    ]
    for code, en, ptn, _ in rows:
        out.append(f'    ("{code}", "{esc(en)}", "{esc(ptn)}"),')
    out.append("];")
    with open(os.path.join(ROOT, "crates/proto/src/countries.rs"), "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"{count} countries")


if __name__ == "__main__":
    main(sys.argv[1])
